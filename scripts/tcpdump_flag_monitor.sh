#!/bin/bash
# ==============================================================================
# 【独立 tcpdump Flag 泄露监控脚本】
# Flag 格式: [A-Z0-9]{31}=  (兼容 ihack26{...})
# 用法：在自己靶机以 root 运行: bash tcpdump_flag_monitor.sh
# ==============================================================================

echo "=== 正在通过 tcpdump 监控 Flag ([A-Z0-9]{31}=) 是否被拿走 ==="
echo "=== 平时屏幕为空白，一旦检测到 Flag 流出立即打印前后上下文 ==="

tcpdump -i any -l -nn -A -s 0 "not port 22" 2>/dev/null | grep --line-buffered -E -B 15 -A 5 "([A-Z0-9]{31}=|ihack26\{)"
